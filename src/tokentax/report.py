"""Write RESULTS.md from results/*.json, so every number in it is reproducible."""

from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Any

from tokentax import registry
from tokentax.languages import BY_CODE
from tokentax.paths import RESULTS, ROOT


def _load(name: str) -> Any:
    return json.loads((RESULTS / f"{name}.json").read_text(encoding="utf-8"))


def _label(key: str) -> str:
    spec = registry.BY_KEY.get(key)
    return spec.label if spec else key


def _lang(code: str) -> str:
    lang = BY_CODE.get(code)
    return lang.name if lang else code


def _table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def build() -> str:
    bench, fair, expl = _load("benchmark"), _load("fairness"), _load("explainer")
    pred, opt, comp, sim = _load("predictor"), _load("optimizer"), _load("compression"), \
        _load("simulator")
    keys = list(bench["english_tokens_per_word"])
    parts: list[str] = ["# Results\n",
                        "Generated by `python -m tokentax.report` from `results/*.json`. "
                        "Do not edit by hand.\n"]

    # 01 heatmap
    cells = {(c["tokenizer"], c["language"], c["style"]): c["premium"] for c in bench["flores"]}
    langs = [c["language"] for c in bench["flores"]
             if c["tokenizer"] == keys[0] and c["style"] == "native"
             and c["language"] != "eng_Latn"]
    rows = []
    for code in langs:
        row = [_lang(code)]
        for k in keys:
            n = cells.get((k, code, "native"))
            r = cells.get((k, code, "roman"))
            row.append(f"{n:.2f}" + (f" / {r:.2f}" if r is not None else ""))
        rows.append(row)
    parts.append("## 1. Token tax by language, style and tokenizer\n")
    parts.append("Tokens relative to English on FLORES-200 devtest (1,012 parallel sentences). "
                 "Each cell: native script / casual romanisation.\n")
    parts.append(_table(["Language", *[_label(k) for k in keys]], rows))
    cheaper = bench["cheaper_style"]
    parts.append("\nLanguages where **native script is cheaper** than casual romanisation: " +
                 ", ".join(f"{_label(k)} {sum(v == 'native' for v in d.values())}/{len(d)}"
                           for k, d in cheaper.items()) + ".\n")

    # codemix
    saving = {(x["tokenizer"], x["language"], x["style"]): x["latin_saving"]
              for x in bench["codemix"]}
    cm_rows = [[_lang(r["language"]), r["style"], str(r["comments"]),
                *[f"{saving[(k, r['language'], r['style'])]:+.0%}" for k in keys]]
               for r in bench["codemix"] if r["tokenizer"] == keys[0]]
    parts.append("### Real code-mixed comments (DravidianCodeMix)\n")
    parts.append("Tokens saved by rewriting each comment fully in Latin letters "
                 "(negative = Latin costs more).\n")
    parts.append(_table(["Language", "Style", "Comments", *[_label(k) for k in keys]], cm_rows))

    # 02 fairness
    parts.append("\n## 2. Language Fairness Index (English = 1.00)\n")
    by_key: dict[str, list[float]] = {}
    for s in fair["scores"]:
        by_key.setdefault(s["tokenizer"], []).append(s["index"])
    parts.append(_table(["Tokenizer", "Mean LFI", "Lowest", "Highest"],
                        [[_label(k), f"{statistics.mean(v):.2f}", f"{min(v):.2f}",
                          f"{max(v):.2f}"] for k, v in by_key.items()]))

    # 03 explainer
    parts.append("\n## 3. Where the extra tokens come from\n")
    parts.append(_table(
        ["Tokenizer", "Language", "From vowel-sign splits", "From missing vocabulary",
         "Byte tokens", "Cuts on morpheme boundary", "Random-cut baseline"],
        [[_label(r["tokenizer"]), _lang(r["language"]), f"{r['vowel_split_share']:.0%}",
          f"{r['vocab_gap_share']:.0%}", f"{r['byte_share']:.0%}",
          f"{r['grammar_alignment']:.1%}" if r["grammar_alignment"] is not None else "–",
          f"{r['alignment_chance']:.1%}" if r["alignment_chance"] is not None else "–"]
         for r in expl["rows"] if r["language"] in ("kan_Knda", "hin_Deva", "tam_Taml")]))

    # 04 predictor
    parts.append("\n## 4. Predicting tokens without the tokenizer\n")
    parts.append(f"Metric: {pred['metric']}, averaged over test sets "
                 "(FLORES devtest in 18 languages, romanised versions, real comments).\n")
    parts.append(_table(["Tokenizer", "Ours (mean / worst set)", "Generic char classes",
                         "chars ÷ 4"],
                        [[_label(k), f"{v['ours']['mean']:.1f}% / {v['ours']['worst']:.1f}%",
                          f"{v['generic']['mean']:.1f}% / {v['generic']['worst']:.1f}%",
                          f"{v['chars_over_4']['mean']:.1f}% / {v['chars_over_4']['worst']:.1f}%"]
                         for k, v in pred["summary"].items()]))

    # 06 optimizer
    parts.append("\n## 5. Format Optimizer (per-sentence choice, meaning-checked)\n")
    orows = [r for r in opt["rows"] if r["tokenizer"] != "*"]
    parts.append(_table(
        ["Tokenizer", "Language", "As typed", "Always casual", "Optimized", "Saving",
         "vs best fixed rule"],
        [[_label(r["tokenizer"]), _lang(r["language"]), f"{r['premium_native']:.2f}×",
          f"{r['premium_casual']:.2f}×", f"{r['premium_optimized']:.2f}×",
          f"{r['saving_vs_native']:.0%}", f"{r['saving_vs_best_fixed']:+.1%}"]
         for r in orows if r["language"] in ("kan_Knda", "hin_Deva", "tam_Taml", "ben_Beng")]))
    amb = [r for r in opt["rows"] if r["tokenizer"] == "*"]
    parts.append("\nSpelling ambiguity of casual romanisation (share of words whose Latin "
                 "spelling matches another word): " +
                 ", ".join(f"{_lang(r['language'])} {r['spelling_ambiguity']:.1%}"
                           for r in amb) + ".\n")

    # 07 compression
    parts.append("## 6. Grammar-aware compression\n")
    parts.append(_table(["Set", "Sentences", "Edited", "Rules used",
                         *[_label(k) for k in keys]],
                        [[r["set"], str(r["sentences"]), f"{r['edited_share']:.0%}",
                          ", ".join(f"{k} {v}" for k, v in r["rules"].items()) or "–",
                          *[f"{r['saving'][k]:.1%}" for k in keys]] for r in comp["rows"]]))

    # 05 simulator
    parts.append("\n## 7. Government chatbot (1 lakh users/day, 4 messages, 70% regional)\n")
    parts.append(_table(["Model", "Language", "Annual cost", "Extra from token tax",
                         "Saved by optimizer (questions only)"],
                        [[_label(r["model"]), _lang(r["language"]),
                          f"₹{r['annual_inr'] / 1e7:.2f} cr",
                          f"₹{r['extra_annual_inr'] / 1e7:.2f} cr",
                          f"₹{r['saved_by_optimizer_annual_inr'] / 1e7:.2f} cr"]
                         for r in sim["rows"] if r["language"] in ("kan_Knda", "hin_Deva")]))
    parts.append(f"\nUSD→INR {sim['usd_to_inr']}. Open-weight models priced like GPT-4o "
                 "(config/prices.json), so differences come from tokenization alone. "
                 "Simulated costs, not API bills.\n")
    parts.extend(_research())
    return "\n".join(parts)


def _pct(x: float, d: int = 1) -> str:
    return f"{x * 100:.{d}f}%"


def _research() -> list[str]:
    if not (RESULTS / "strategies.json").exists():
        return []
    ver, st = _load("verification"), _load("strategies")
    lfi, eff = _load("lfi_sensitivity"), _load("efficiency")
    sm = ver["summary"]
    out = ["\n## 8. Meaning-safety verifier (FLORES devtest, controlled changes)\n",
           f"Threshold: chrF {ver['threshold']['chrf']} ({ver['threshold']['source']}). "
           f"{ver['test_rows']} test pairs in {len(ver['languages'])} languages.\n",
           _table(["", "Safe rewrites accepted", "Unsafe changes caught"],
                  [["Full verifier", _pct(sm["safe_accepted"]), _pct(sm["unsafe_caught"])],
                   ["Similarity score only", _pct(sm["similarity_only"]["safe_accepted"]),
                    _pct(sm["similarity_only"]["unsafe_caught"])]]),
           "\n",
           _table(["Change", "Safe?", "n", "Handled correctly (ours)", "Similarity only"],
                  [[k["kind"].split(":")[1], "yes" if k["safe"] else "no", str(k["n"]),
                    _pct(k["accepted"] if k["safe"] else 1 - k["accepted"]),
                    _pct(k["accepted_similarity_only"] if k["safe"]
                         else 1 - k["accepted_similarity_only"])] for k in ver["by_kind"]]),
           "\nLayer ablation (remove one check):\n",
           _table(["Removed check", "Unsafe caught", "Safe accepted"],
                  [[a["removed_check"], _pct(a["unsafe_caught"]), _pct(a["safe_accepted"])]
                   for a in ver["ablation"]]),
           "\nThe unsafe changes are synthetic and of the types the checks target; this is an "
           "upper bound for those types, not a general guarantee.\n",
           f"\n## 9. Strategies ({st['sentences_per_language']} devtest sentences × "
           f"{len(st['languages'])} languages × 7 tokenizers)\n",
           _table(["Strategy", "Token reduction", "Meaning-safe outputs"],
                  [[p["strategy"], _pct(p["token_reduction"]), _pct(p["meaning_safe_rate"])]
                   for p in st["pareto"]]),
           "\nPaired comparison with the best single format per model and language (chosen on "
           "dev data): mean per-sentence difference in saving, 95% bootstrap CI, sign-flip "
           "permutation p.\n",
           _table(["Tokenizer", "Ours", "Best fixed", "Difference (pts)", "95% CI", "p"],
                  [[_label(r["tokenizer"]), _pct(r["adaptive_saving"]),
                    _pct(r["best_fixed_saving"]), f"{r['test']['mean_diff'] * 100:+.2f}",
                    f"[{r['test']['ci95'][0] * 100:+.2f}, {r['test']['ci95'][1] * 100:+.2f}]",
                    "<0.001" if r["test"]["p_value"] < 0.001 else f"{r['test']['p_value']:.3f}"]
                   for r in st["per_tokenizer"]]),
           "\nAblation:\n",
           _table(["Variant", "Token reduction", "Unsafe outputs"],
                  [[a["variant"], _pct(a["token_reduction"]),
                    _pct(a["unsafe_outputs"]) if "unsafe_outputs" in a else "0.0%"]
                   for a in st["ablation"]]),
           "\nDomain shift:\n",
           _table(["Domain", "Strategy", "Token reduction", "Meaning-safe"],
                  [[d["domain"], d["strategy"], _pct(d["token_reduction"]),
                    _pct(d["meaning_safe_rate"])] for d in st["domains"]]),
           "\nRejections by first failed check:\n",
           _table(["Candidate", "Check", "Count"],
                  [[f["candidate"], f["reason"], str(f["count"])]
                   for f in st["failure_by_candidate"][:15]]),
           f"\nOptimisation latency per sentence, all 7 tokenizers: median "
           f"{st['latency_ms']['p50']:.0f} ms, 95th percentile {st['latency_ms']['p95']:.0f} ms "
           f"(CPU).\n",
           "\n## 10. Language Fairness Index sensitivity\n",
           f"{lfi['formula']}. Over {lfi['draws']} random Dirichlet weightings, Kendall τ with the "
           f"equal-weight ranking: mean {lfi['kendall_tau']['mean']:.3f}, 5th percentile "
           f"{lfi['kendall_tau']['p05']:.3f}, minimum {lfi['kendall_tau']['min']:.3f}. The worst "
           f"pair ({lfi['worst_pair']}) stays worst in {_pct(lfi['worst_pair_stable'], 0)}.\n",
           _table(["Dropped part", "Kendall τ"],
                  [[r["dropped_part"], f"{r['kendall_tau']:.3f}"] for r in lfi["leave_one_out"]]),
           *_counterfactual(),
           "\n## 11. Efficiency (CPU)\n",
           f"Optimise + verify one sentence for 7 tokenizers: "
           f"{eff['plan_ms_per_sentence_all_tokenizers']:.0f} ms; process memory "
           f"{eff['process_rss_mb']:.0f} MB.\n",
           _table(["Tokenizer", "Load (ms)", "Encode per sentence (ms)"],
                  [[_label(r["tokenizer"]), f"{r['load_ms']:.0f}",
                    f"{r['encode_ms_per_sentence']:.3f}"] for r in eff["tokenizers"]])]
    return out


def write(path: Path = ROOT / "RESULTS.md") -> Path:
    path.write_text(build(), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write())


def _counterfactual() -> list[str]:
    if not (RESULTS / "counterfactual.json").exists():
        return []
    cf = _load("counterfactual")
    return ["\n## 10b. Fix the tokenizer or fix the text?\n",
            f"Pre-tokenizer patched to keep vowel signs inside words, same vocabulary; "
            f"{cf['sentences_per_language']} devtest sentences x "
            f"{len(cf['languages'])} languages.\n",
            _table(["Tokenizer", "Splits at vowel signs", "Saving: fixed pre-tokenizer",
                    "Saving: BhashaToken rewrite"],
                   [[_label(r["tokenizer"]), "yes" if r["has_split"] else "no",
                     _pct(r["saving_fixed_pretokenizer"], 2), _pct(r["saving_bhashatoken"])]
                    for r in cf["per_tokenizer"]]),
            "\nThe vocabulary was learned with the split, so fixing the split alone saves "
            "almost nothing; a real fix needs a retrained vocabulary and model.\n"]
